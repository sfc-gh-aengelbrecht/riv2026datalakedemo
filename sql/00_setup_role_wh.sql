-- RIV 2026 data lake demo - step 0: demo role and warehouse
-- Run as ACCOUNTADMIN in a Snowsight SQL worksheet.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS RIV_DEMO_RL COMMENT = 'Owns all RIV 2026 data lake demo objects';
GRANT ROLE RIV_DEMO_RL TO ROLE SYSADMIN;
SET MY_USER = CURRENT_USER();
GRANT ROLE RIV_DEMO_RL TO USER IDENTIFIER($MY_USER);

GRANT CREATE DATABASE ON ACCOUNT TO ROLE RIV_DEMO_RL;
GRANT CREATE WAREHOUSE ON ACCOUNT TO ROLE RIV_DEMO_RL;
GRANT CREATE INTEGRATION ON ACCOUNT TO ROLE RIV_DEMO_RL;
GRANT CREATE EXTERNAL VOLUME ON ACCOUNT TO ROLE RIV_DEMO_RL;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE RIV_DEMO_RL;

USE ROLE RIV_DEMO_RL;

-- Any warehouse works. The original demo uses an adaptive warehouse; a standard
-- XSMALL is enough if adaptive warehouses are not available in your account.
CREATE WAREHOUSE IF NOT EXISTS RIV_DEMO_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  COMMENT = 'Warehouse for the RIV retail distribution Iceberg demo';

USE WAREHOUSE RIV_DEMO_WH;
