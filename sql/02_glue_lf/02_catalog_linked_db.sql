-- Pattern 2, step 2: catalog-linked database over Glue database rivdemo_2026
-- Run only after the sandbox admin has added your trust entry.
-- The tables are shared by everyone using the sandbox: do not DROP or DELETE from them.

USE ROLE RIV_DEMO_RL;
USE WAREHOUSE RIV_DEMO_WH;

SELECT SYSTEM$VERIFY_CATALOG_INTEGRATION('RIV_DEMO_2026_GLUE_CAT_INT');

CREATE DATABASE IF NOT EXISTS RIV2026DATALAKEDEMO
  LINKED_CATALOG = (
    CATALOG = 'RIV_DEMO_2026_GLUE_CAT_INT'
    ALLOWED_NAMESPACES = ('rivdemo_2026')
    NAMESPACE_MODE = IGNORE_NESTED_NAMESPACE
    SYNC_INTERVAL_SECONDS = 30
    ALLOWED_WRITE_OPERATIONS = ALL);

SELECT SYSTEM$CATALOG_LINK_STATUS('RIV2026DATALAKEDEMO');
SHOW ICEBERG TABLES IN DATABASE RIV2026DATALAKEDEMO;
